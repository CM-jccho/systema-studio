export const copy: Record<Locale, Copy> = { ko, en };

export function pick(value: { ko: string; en: string }, locale: Locale): string {
  const primary = value[locale];
  if (primary && primary.trim()) return primary;
  const other = locale === "ko" ? value.en : value.ko;
  return other || "";
}
